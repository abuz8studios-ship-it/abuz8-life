# ABUZ8 LIFE build — fuse modules into one double-clickable file.
# Reads and writes through explicit UTF-8 without BOM; Get-Content/Set-Content
# round-trips mangle em-dashes and geometric glyphs into double-encoded mojibake.
$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$utf8 = New-Object System.Text.UTF8Encoding($false)
function ReadUtf8($p) { [System.IO.File]::ReadAllText($p, $utf8) }

$css = ReadUtf8 (Join-Path $here 'life-style.css')

# data first, then model, then renderers
$js = (@(
  'life-system.js',    # PROBE GPUS HOST VOLUMES PORTS PROCS REPOS SECRETS SCHEDULE CONNECTORS
  'life-fusion-data.js', # FUSION CODEGRAPH SEOAUDIT — generated by fusion_build.py
  'life-items.js',     # PROJECT_ITEMS
  'life-logic.js',     # model, state, drawer, routing
  'life-views.js',     # the six lenses
  'life-surfaces.js',  # board / calendar / crm / security / connectors / live
  'life-fusion.js',    # CEO SEO Graph Dealer Planner — fusion surfaces
  'life-theme.js',     # night/day toggle + persistence (must load before boot)
  'life-brainmap.js',  # project→anatomy mapping + live counts
  'life-holobrain.js', # native holographic brain renderer
  'life-scroll.js',    # scroll reveal + progress + postRender hooks
  'life-graph3d.js',   # live Three.js code graph (vendored, no CDN)
  'life-isnad.js',     # ISNAD Möbius brain graph — unified layer
  'life-missions.js',  # Missions: Kanban board + CRM lanes (MISSION_INDEX + war plan)
  'life-live.js',      # polling client — must load after the arrays it swaps
  'life-actions.js'    # gated action surface
) | ForEach-Object {
  $p = Join-Path $here $_
  if (-not (Test-Path $p)) { throw "missing module: $_" }
  "/* ===== $_ ===== */`n" + (ReadUtf8 $p)
}) -join "`n"

$html = ReadUtf8 (Join-Path $here 'life-frame.html')
$html = $html.Replace('/*__CSS__*/', $css).Replace('/*__JS__*/', $js)

$out = Join-Path $here 'LIFE.html'
[System.IO.File]::WriteAllText($out, $html, $utf8)

$kb = [math]::Round((Get-Item $out).Length / 1KB, 1)
Write-Host "built LIFE.html  ($kb KB)" -ForegroundColor Green
Write-Host "open: $out" -ForegroundColor Cyan
